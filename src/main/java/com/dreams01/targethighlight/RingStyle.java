package com.dreams01.targethighlight;

/** Visual style of the ring under the target. */
public enum RingStyle {
    /** A plain flat ring. */
    SOLID,
    /** Several curved arcs on two layers that turn in opposite directions. */
    SEGMENTED_ARC,
    /** Two thin circles with a subtle pattern of glyph strokes between them. */
    RUNIC,
    /** Enchanting-table (Standard Galactic) glyphs orbiting along the ring path. */
    ROTATING_RUNES,
    /** No outline: small glowing lights orbit the footprint. */
    MOTES
}
